  await page.getByRole('button',{name:'05 Review',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Finished means reviewed.'})).toBeVisible();
  await capture('02-experience-exploded');
  await page.getByRole('button',{name:'Switch to dark appearance'}).click();
  await capture('03-experience-dark');
  await page.getByRole('button',{name:'Switch to light appearance'}).click();
  await page.getByRole('link',{name:'Step inside Studio'}).click();
  await expect(page.getByRole('heading',{name:'Your boundary. Your decision.'})).toBeVisible();
  await capture('04-studio-approval-light');
  await page.getByRole('button',{name:'Inspect full request'}).click();
  await capture('05-exact-request');
  await page.keyboard.press('Escape');
  await expect(page.getByRole('button',{name:'Inspect full request'})).toBeFocused();
  await page.getByRole('button',{name:'Changes 2',exact:true}).click();
  await capture('06-changes-light');
  await page.getByRole('button',{name:'test_confirm.py',exact:true}).click();
  await expect(page.locator('.diff-meta code')).toHaveText('src/payments/test_confirm.py');
  await page.getByLabel('Changed lines only').check();
  await expect(page.locator('.code-line.context')).toHaveCount(0);
  await page.getByRole('button',{name:'Checks',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Verification has not run'})).toBeVisible();
  await capture('07-checks-pending');
  await page.getByRole('button',{name:'Evidence',exact:true}).click();
  await page.getByLabel('Inspect a captured sample event').fill('4');
  await expect(page.locator('#event-title')).toHaveText('Review');
  await capture('08-evidence');
  await page.getByRole('button',{name:'Approve sample',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Permission granted.'})).toBeVisible();
  await expect(page.locator('.outcome-facts')).toContainText('Not run');
  await expect(page.getByRole('status')).toContainText('Nothing executed');
  await capture('09-approved-not-verified');
  await page.getByRole('button',{name:'Return to approval sample'}).click();
  await page.getByRole('button',{name:'Reject',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Request rejected.'})).toBeVisible();
  await capture('10-rejected');
  await page.getByRole('button',{name:'Verified',exact:true}).click();
  await page.getByRole('button',{name:'Checks',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Checks passed in this sample'})).toBeVisible();
  await capture('11-verified');
  await page.getByRole('button',{name:'Failed',exact:true}).click();
  await expect(page.getByRole('heading',{name:'A useful failure.'})).toBeVisible();
