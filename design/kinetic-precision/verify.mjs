  await capture('13-failed-dark');
  await page.getByRole('button',{name:'New task',exact:true}).click();
  await page.getByLabel('Task',{exact:true}).fill('My deliberately unsubmitted draft.');
  await capture('14-draft');
  await page.keyboard.press('Escape');
  await page.getByRole('button',{name:'New task',exact:true}).click();
  await expect(page.getByLabel('Task',{exact:true})).toHaveValue('My deliberately unsubmitted draft.');
  await page.getByRole('button',{name:'Keep demo draft'}).click();
  await expect(page.getByRole('status')).toContainText('No run was dispatched');
  await page.keyboard.press('Control+k');
  await page.getByRole('textbox',{name:'Search commands'}).fill('nonsense-no-result');
  await expect(page.getByText('No matching commands.')).toBeVisible();
  await page.getByRole('textbox',{name:'Search commands'}).fill('changes');
  await capture('15-command-search');
  await page.keyboard.press('Enter');
  await expect(page.getByRole('heading',{name:'Small change. Clear intent.'})).toBeVisible();
  await page.getByRole('button',{name:'Workspace & policy'}).click();
  await capture('16-workspace');
  await page.keyboard.press('Escape');
  await page.getByRole('button',{name:'023 Improve search ranking'}).click();
